# build_assets_repo.py [tag]: large pictures and sounds out of the DLL (UCAssetStore, same scheme as Unknown's Atlas).
#
# Copies every file that UC loads from the asset repository at run time to ../UnknownsCollection-Assets/files/,
# writes catalog.json there and generates UCAssetCatalog.g.cs (file name, resource name, size, SHA-256, tag).
# Files in the asset folder that are no longer in the catalog are deleted. Then commit the asset repository,
# set the tag (v1, v2 ...) and push; a DLL always downloads from the tag in its catalog.
#
# Outsourced: button animation frames (Resources/anim), hats (Resources/hats), the Void eject scene pictures
# (task_eject_*), the music (werewolf form, pelican hunt, reactor) and the longer sound effects (OUT_SOUNDS).
# Kept in the DLL: localization, button icons, symbols, kill-overlay parts, short sounds, eject_void.json.
# The tool refuses to run if an outsourced file is still embedded by the csproj.

import fnmatch
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESDIR = ROOT / "Resources"
REPO = ROOT.parent / "UnknownsCollection-Assets"
CS = ROOT / "UCAssetCatalog.g.cs"
CSPROJ = ROOT / "UnknownsCollection.csproj"
PREFIX = "UnknownsCollection.Resources."

# longer sound effects (about 20 KB and more as Ogg); everything shorter stays embedded
OUT_SOUNDS = ["tesla_warning", "tesla_promote", "tesla_discharge", "maniac_fuse", "maniac_explosion",
              "poltergeist_manifest", "poltergeist_poof", "poltergeist_reveal", "collector_win",
              "silencer_silence", "werewolf_howl", "werewolf_transform"]

# (sub folder, patterns)
GROUPS = [
    ("anim", ["*.png"]),
    ("hats", ["*.png"]),
    ("", ["task_eject_*.png", "task_eject_*.jpg",
          "werewolf_form_music*.ogg", "pelican_hunt_music*.ogg", "pelican_hunt_intro.ogg", "pelican_hunt_end.ogg",
          "reactor_*.ogg"] + [s + ".ogg" for s in OUT_SOUNDS]),
]


def collect():
    out = {}
    for sub, pats in GROUPS:
        base = RESDIR / sub if sub else RESDIR
        for pat in pats:
            found = list(base.glob(pat))
            if not found:
                sys.exit(f"pattern without files: {sub}/{pat}")
            for p in found:
                res = PREFIX + (sub + "." if sub else "") + p.name
                name = res[len(PREFIX):]
                out[name] = (p, res)
    return [(name,) + out[name] for name in sorted(out)]


def embedded_globs():
    text = re.sub(r"<!--.*?-->", "", CSPROJ.read_text(encoding="utf-8"), flags=re.S)
    globs = []
    for inc in re.findall(r'<EmbeddedResource\s+Include="([^"]+)"', text):
        globs += [g.strip().replace("\\", "/") for g in inc.split(";") if g.strip()]
    return globs


def main():
    tag = sys.argv[1] if len(sys.argv) > 1 else "v1"
    files = collect()
    globs = embedded_globs()
    double = [p for _, p, _ in files if any(fnmatch.fnmatch(p.relative_to(ROOT).as_posix(), g) for g in globs)]
    if double:
        sys.exit("outsourced AND embedded by the csproj:\n  " + "\n  ".join(str(p.relative_to(ROOT)) for p in double))
    out = REPO / "files"
    out.mkdir(parents=True, exist_ok=True)
    keep = {name for name, _, _ in files}
    removed = 0
    for old in out.iterdir():
        if old.is_file() and old.name not in keep:
            old.unlink()
            removed += 1
    entries = []
    for name, p, res in files:
        data = p.read_bytes()
        entries.append({"name": name, "res": res, "size": len(data), "sha256": hashlib.sha256(data).hexdigest()})
        dst = out / name
        if not dst.exists() or dst.read_bytes() != data:
            shutil.copyfile(p, dst)
    (REPO / "catalog.json").write_text(json.dumps({"tag": tag, "files": entries}, indent=1), encoding="utf-8")
    lines = ["// Unknown's Collection - Copyright (C) 2026 DaUnknown-0",
             "// Licensed under GPL-3.0-or-later. See LICENSE for details.",
             "//",
             "// GENERATED by tools/build_assets_repo.py - DO NOT EDIT BY HAND.",
             "// Files UC loads from the asset repository (UCAssetStore): file name in the repository, resource name",
             "// the code asks for, size and SHA-256.",
             "",
             "namespace UnknownsCollection {",
             "    internal static class UCAssetCatalog {",
             f"        public const string Tag = \"{tag}\";",
             "",
             "        public static readonly (string Name, string Res, long Size, string Sha256)[] Files = {"]
    for e in entries:
        lines.append(f"            (\"{e['name']}\", \"{e['res']}\", {e['size']}L, \"{e['sha256']}\"),")
    lines += ["        };", "    }", "}", ""]
    CS.write_text("\n".join(lines), encoding="utf-8")
    total = sum(e["size"] for e in entries)
    print(f"{len(entries)} files, {total / 1048576:.1f} MB -> {out} ({removed} old removed)")
    print(f"catalog {tag} -> {CS.name}")


if __name__ == "__main__":
    main()
